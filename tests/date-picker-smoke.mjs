  await win.mouse.click(10,100);
  assert.equal(await win.locator('#modal').evaluate(el=>el.open),true);
  assert.equal(await win.locator('.date-picker-popover').count(),0);
  await win.keyboard.press('Escape');await win.locator('#modal').waitFor({state:'hidden'});
  checks.push('manual month drafts survive state broadcasts; month grid and year navigation update the journal once; blue and pink themes work; outside click closes only picker and Escape then closes parent');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,checks,isolatedData:userData,installerPayload:!!process.env.TIDE_TEST_APP_ROOT}));
