import { _electron as electron } from 'playwright-core';
import { mkdtemp, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const userData = await mkdtemp(path.join(tmpdir(), 'tide-pet-polish-v5-'));
const env = { ...process.env, TIDE_TEST_DATA: userData };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ executablePath: path.join(root, 'node_modules/electron/dist/electron.exe'), args: [path.join(root, 'tests/launch-smoke.cjs')], env, timeout: 30000 });
const errors = [], checks = [];
try {
  await app.firstWindow();
  let pet;
  for (let index = 0; index < 100; index += 1) {
    pet = app.windows().find(window => window.url().endsWith('/pet.html'));
    if (pet) break;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.ok(pet);
  pet.on('pageerror', error => errors.push(error.message));
  pet.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await pet.clock.install({ time: new Date() });
  await pet.reload();
  await pet.waitForFunction(() => document.querySelector('.pet-stage').dataset.behavior === 'awake');
  const petBounds = () => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().endsWith('/pet.html')).getBounds());
  const originalBounds = await petBounds();
  const before = (await pet.evaluate(() => window.petAPI.loadState())).moods.length;
  await pet.clock.fastForward(8000);
  assert.ok(await pet.locator('.pet-stage').evaluate(element => element.classList.contains('is-blinking')));
  const eyeAnimations = await pet.locator('.eye').evaluateAll(elements => elements.map(element => ({ name: getComputedStyle(element).animationName, delay: getComputedStyle(element).animationDelay })));
  assert.deepEqual(eyeAnimations, [{ name: 'soft-blink', delay: '0s' }, { name: 'soft-blink', delay: '0.027s' }]);
  await pet.clock.runFor(500);
  assert.ok(!await pet.locator('.pet-stage').evaluate(element => element.classList.contains('is-blinking')));
  checks.push('natural blink with offset eyelids');
  await pet.mouse.move(270, 200);
  await pet.waitForTimeout(650);
  const gaze = await pet.locator('.eye-gaze').evaluate(element => { const m = new DOMMatrix(getComputedStyle(element).transform); return { x: m.e, y: m.f }; });
  assert.ok(gaze.x > 0 && gaze.x <= 3.2 && Math.abs(gaze.y) <= 2, JSON.stringify(gaze));
  await pet.clock.runFor(2600);
  await pet.waitForTimeout(650);
  const returnedGaze = await pet.locator('.eye-gaze').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).e);
  assert.ok(Math.abs(returnedGaze) < .01);
  const fin = await pet.locator('.fin-left,.fin-right,.tail').evaluateAll(elements => elements.map(element => ({ delay: getComputedStyle(element).animationDelay, duration: getComputedStyle(element).animationDuration })));
  assert.equal(new Set(fin.map(item => item.delay)).size, 3);
  assert.notEqual(fin[0].duration, fin[2].duration);
  assert.equal((await pet.evaluate(() => window.petAPI.loadState())).moods.length, before);
  checks.push('bounded gaze returns to neutral', 'asynchronous fins and tail', 'micro motion never records user activity');

  await pet.evaluate(() => window.petAPI.petAction('pet'));
  await pet.waitForTimeout(80);
  const firstLine = await pet.locator('#speech-text').textContent();
  assert.ok(firstLine.length < 20);
  await pet.evaluate(() => window.petAPI.petAction('nuzzle'));
  await pet.waitForTimeout(80);
  assert.equal(await pet.locator('#speech-text').textContent(), firstLine);
  // A different gesture follows the current one; it no longer resets a pose mid-motion.
  await pet.waitForFunction(() => document.querySelector('.pet-stage').classList.contains('action-nuzzle'));
  await pet.mouse.move(160, 325);
  await pet.waitForTimeout(500);
  const layout = await pet.locator('#speech,.pet-controls').evaluateAll(elements => elements.map(element => { const r = element.getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom }; }));
  for (const bounds of layout) assert.ok(bounds.left >= 0 && bounds.right <= 320 && bounds.top >= 0 && bounds.bottom <= 370);
  assert.equal(await pet.locator('#speech-text').evaluate(element => getComputedStyle(element).webkitLineClamp), 'none');
  await mkdir(path.join(root, 'screenshots'), { recursive: true });
  await pet.screenshot({ path: path.join(root, 'screenshots/pet-v05-bubble.png'), omitBackground: true });
  checks.push('short replies with silent repeat gesture', 'bubble and controls fit native window');

  const longName = '圆滚鲨鱼'.repeat(10);
  await pet.evaluate(async name => { const state = await window.petAPI.loadState(); state.settings.name = name; await window.petAPI.saveState(state); }, longName);
  await pet.waitForFunction(name => document.title.startsWith(name), longName);
  assert.ok((await pet.locator('#speech-text').textContent()).includes(longName));
  const longNameFit = await pet.locator('#speech').evaluate(element => { const outer = element.getBoundingClientRect(), inner = document.getElementById('speech-text').getBoundingClientRect(); return outer.top >= 0 && outer.bottom <= 370 && inner.bottom <= outer.bottom; });
  assert.ok(longNameFit);
  const longError = '外观暂时无法加载。'.repeat(25);
  await pet.evaluate(message => document.dispatchEvent(new CustomEvent('live2d-status', { detail: { state: 'error', message } })), longError);
  assert.equal(await pet.locator('#speech-text').textContent(), longError);
  const errorFit = await pet.locator('#speech-text').evaluate(element => { const outer = document.getElementById('speech').getBoundingClientRect(), inner = element.getBoundingClientRect(); return inner.bottom <= outer.bottom && element.scrollHeight > element.clientHeight && element.tabIndex === 0 && getComputedStyle(element).getPropertyValue('-webkit-app-region') === 'no-drag'; });
  assert.ok(errorFit);
  checks.push('40-character name and long skin error stay within the bubble');

  const reminder = '用药提醒：按已保存计划查看今天的记录。' + '这是一条用于检验长内容完整显示的测试提醒，请打开手账核对记录。'.repeat(6);
  await app.evaluate(({ BrowserWindow }, message) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().endsWith('/pet.html')).webContents.send('pet:action', { action: 'reminder', message }), reminder);
  await pet.waitForFunction(expected => document.getElementById('speech-text').textContent === expected, reminder);
  const scroll = await pet.locator('#speech-text').evaluate(element => ({ actual: element.scrollHeight, visible: element.clientHeight, overflow: getComputedStyle(element).overflowY, region: getComputedStyle(element).getPropertyValue('-webkit-app-region') }));
  assert.ok(scroll.actual > scroll.visible);
  assert.equal(scroll.overflow, 'auto');
  assert.equal(scroll.region, 'no-drag');
  await pet.locator('#speech-text').focus();
  await pet.keyboard.press('End');
  await pet.waitForTimeout(500);
  assert.ok(await pet.locator('#speech-text').evaluate(element => element.scrollTop > 0));
  await pet.locator('#speech-text').evaluate(element => { element.scrollTop = 0; });
  await pet.screenshot({ path: path.join(root, 'screenshots/pet-v05-reminder.png'), omitBackground: true });
  await pet.clock.fastForward(46000);
  assert.ok(!await pet.locator('#speech').evaluate(element => element.classList.contains('is-hidden')));
  await pet.evaluate(() => window.petAPI.petAction('nuzzle'));
  await pet.waitForTimeout(50);
  assert.equal(await pet.locator('#speech-text').textContent(), reminder);
  await pet.locator('#speech-open').click();
  assert.ok(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(window => window.webContents.getURL().endsWith('/index.html')).isVisible()));
  await pet.locator('#speech-open').evaluate(element => element.blur());
  await pet.clock.runFor(2000);
  assert.ok(await pet.locator('#speech').evaluate(element => element.inert && element.classList.contains('is-hidden')));
  checks.push('long reminder remains intact and scrollable', 'focused reading stays visible and has priority', 'reminder opens dashboard', 'hidden bubble excluded from keyboard focus');

  await pet.evaluate(async () => { const state = await window.petAPI.loadState(); state.settings.reducedMotion = true; await window.petAPI.saveState(state); });
  await pet.waitForFunction(() => document.documentElement.classList.contains('reduced-motion'));
  await pet.mouse.move(280, 180);
  await pet.clock.fastForward(12000);
  assert.equal(await pet.locator('.eye-gaze').evaluate(element => getComputedStyle(element).transform), 'none');
  assert.equal(await pet.locator('.tail').evaluate(element => getComputedStyle(element).animationName), 'none');
  assert.ok(!await pet.locator('.pet-stage').evaluate(element => element.classList.contains('is-blinking')));
  await pet.evaluate(async () => { const state = await window.petAPI.loadState(); state.settings.reducedMotion = false; await window.petAPI.saveState(state); });
  await pet.waitForFunction(() => !document.documentElement.classList.contains('reduced-motion'));
  await pet.emulateMedia({ reducedMotion: 'reduce' });
  await pet.mouse.move(60, 200);
  await pet.clock.fastForward(12000);
  assert.equal(await pet.locator('.eye-gaze').evaluate(element => getComputedStyle(element).transform), 'none');
  assert.equal(await pet.locator('.fin-left').evaluate(element => getComputedStyle(element).animationName), 'none');
  assert.ok(!await pet.locator('.pet-stage').evaluate(element => element.classList.contains('is-blinking')));
  checks.push('application and OS reduced motion stop gaze and micro animations');
  assert.deepEqual(await petBounds(), originalBounds);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, checks, errors, isolatedData: userData }));
} finally { await app.close(); }
